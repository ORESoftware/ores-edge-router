#!/usr/bin/env node
// Render wrangler.toml from router.config.json. Usage:
//   node scripts/render-wrangler.mjs [path/to/router.config.json] [--out wrangler.toml] [--kv-id <id>] [--main <entry>]
// The config is the authority; the TOML is generated and should be committed
// so `wrangler deploy` needs no extra flags.

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { normalizeConfig, missingCanonicalLabels } from '../src/config.mjs';

const args = process.argv.slice(2);
const cfgPath = args.find((a) => !a.startsWith('--')) ?? 'router.config.json';
const out = args.includes('--out') ? args[args.indexOf('--out') + 1] : 'wrangler.toml';
const kvId = args.includes('--kv-id') ? args[args.indexOf('--kv-id') + 1] : 'REPLACE_WITH_KV_NAMESPACE_ID';
const main = args.includes('--main') ? args[args.indexOf('--main') + 1] : 'node_modules/@oresoftware/ores-edge-router/src/index.mjs';

const raw = JSON.parse(readFileSync(resolve(cfgPath), 'utf8'));
const config = normalizeConfig(raw);
const missing = missingCanonicalLabels(config);

const routes = Object.values(config.hosts)
  .map((h) => `  { pattern = "${h.publicHost}/*", zone_name = "${config.domain}" },`)
  .join('\n');

const toml = `# GENERATED by ores-edge-router/scripts/render-wrangler.mjs from ${cfgPath} — do not edit by hand.
# org: ${config.org}   domain: ${config.domain}${config.linearProject ? `   linear: ${config.linearProject}` : ''}
name = "${config.org.toLowerCase()}-edge-router"
main = "${main}"
compatibility_date = "2026-08-01"
workers_dev = false
${missing.length ? `# WARNING: canonical subdomains not declared yet: ${missing.join(', ')}\n` : ''}
routes = [
${routes}
]

[triggers]
crons = ["* * * * *"]

[[kv_namespaces]]
binding = "HEALTH"
id = "${kvId}"

[vars]
ROUTER_CONFIG = '''${JSON.stringify(config)}'''

[observability]
enabled = true
`;

writeFileSync(resolve(out), toml);
console.log(`[render] ${cfgPath} -> ${out}: ${Object.keys(config.hosts).length} hosts on ${config.domain}${missing.length ? ` (missing canonical: ${missing.join(', ')})` : ''}`);
